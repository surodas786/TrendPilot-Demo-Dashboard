// Step 12 DRY RUN: the planned pilot flow, end to end, with mocked MEXC responses. Real TradingView
// alerts, durable intents and the worker job loop drive the pilot-guarded MEXC adapter against a
// stateful mock exchange. Nothing leaves the process: there is no live transport in this build.
// The test writes a transcript (redacted requests, results, reconciliation) to
// test-results/pilot-rehearsal.md. Capabilities are marked VERIFIED only as MOCK evidence here.
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { and, eq } from 'drizzle-orm';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import {
  activatePilot,
  approvePilot,
  buildSignedRequest,
  createPilot,
  deactivatePilot,
  mexcVenue,
  openPilot,
  PILOT_REQUIRED_CHECKS,
  pilotGuardedVenue,
  pilotReadiness,
  recordPilotCheck,
  redactHeaders,
  requestExit,
  resumePilotEntries,
  schema,
  type ExecutionVenue,
  type PilotCheckId,
  type PilotGuardEvent
} from '@trendpilot/db';
import { Decimal } from '@trendpilot/domain';
import { setTestClock } from '@/server/clock';
import { BTC, direct, teardown, userId, USERS } from '../helpers';
import { MockMexc } from '../mexcMock';
import { clock, deliver, drain, M15, openFromAlert, plus, positionsOf, reconciled } from '../paperReplay';
import { recordMarketTick } from '@trendpilot/db';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
const A = USERS.investorA.email;
const B = USERS.investorB.email;
const DUMMY = { apiKey: 'mx0-DRYRUN-not-a-key', secretKey: 'DRYRUN-not-a-secret' };
const MOCK_EVIDENCE = { OPEN_WITH_ATTACHED_STOP: 'VERIFIED', REDUCE_ONLY_CLOSE: 'VERIFIED', STOP_RESIZE_AFTER_PARTIAL_CLOSE: 'VERIFIED' } as const;
const LIMITS = { maxOrderContracts: '15', maxOrderNotionalUsdt: '110', maxLeverage: 5, maxExposureUsdt: '110' };
const D = (v: Decimal.Value) => new Decimal(v);

const mexc = new MockMexc();
mexc.positionMode = 2; // the pilot account is in One-way mode (required for Live entries)
mexc.now = () => clock.now.getTime(); // exchange time follows the rehearsal clock
const events: PilotGuardEvent[] = [];
const out: string[] = ['# TrendPilot live pilot — DRY RUN with mocked MEXC responses', '', `Generated by apps/web/test/api/pilotRehearsal.test.ts. No request left the process; live order submission is disabled.`, ''];
const log = (...lines: string[]) => out.push(...(lines.length ? lines : ['']));
const code = (o: unknown) => log('```json\n' + JSON.stringify(o, null, 2) + '\n```');

let adminId = '';
let venueGen = 0;
const buildVenue = (): ExecutionVenue => {
  venueGen += 1; // a new instance per "worker process"
  return pilotGuardedVenue(direct.db, mexcVenue({ requester: mexc, symbolFor: async () => 'BTC_USDT', positionMode: 'ONE_WAY', capabilities: MOCK_EVIDENCE, confirm: { attempts: 2, delayMs: 0 }, sleep: async () => {} }), { onEvent: (e) => events.push(e) });
};
let venue: ExecutionVenue;
const hooks = () => ({ venue });

/** Moves to `iso`, writes a fixture quote there (the entry checks need a fresh price) and sets the mock price. */
const priceAt = async (iso: string, mid: string) => {
  clock.now = new Date(iso);
  setTestClock(() => clock.now);
  mexc.price.BTC_USDT = mid;
  await recordMarketTick(direct.db, { instrumentId: BTC, asOf: clock.now, bid: D(mid).minus('0.5').toFixed(), ask: D(mid).plus('0.5').toFixed(), mark: mid, last: mid });
};
const alert = async (action: 'BULLISH_FLIP' | 'CLOSE_LONG', barOpen: string, mid = '65000') => {
  await priceAt(new Date(new Date(barOpen).getTime() + M15 + 3000).toISOString(), mid);
  expect(await deliver(action, new Date(barOpen))).toBe(202);
  return drain(clock.now, direct.db, hooks());
};
const later = async (seconds: number) => {
  clock.now = plus(clock.now, seconds);
  setTestClock(() => clock.now);
  return drain(clock.now, direct.db, hooks());
};
const intentsOf = async (email: string) => direct.db.select().from(schema.orderIntents).where(eq(schema.orderIntents.ownerId, await userId(email))).orderBy(schema.orderIntents.createdAt);
const openPos = async () => (await positionsOf(A)).find((p) => p.status === 'OPEN');
const creates = () => mexc.creates().map((c) => c.body as Record<string, unknown>);
const redacted = (body: Record<string, unknown>) => {
  const r = buildSignedRequest(DUMMY, 'POST', '/api/v1/private/order/create', body, String(clock.now.getTime()), 10);
  return { method: r.method, url: `https://api.mexc.com${r.url}`, headers: redactHeaders(r.headers), body: JSON.parse(r.body!) };
};
const pilot = async () => (await openPilot(direct.db))!;

beforeAll(async () => {
  venue = buildVenue();
  // Investor A: 20 USDT × 5, stop 1.5 % (mark), fixed TP 3 %. B keeps defaults and is NOT allowlisted.
  await openFromAlert({
    a: { orderCostUsdt: '20', leverage: 5 },
    hooks: hooks(),
    market: async () => {
      adminId = await userId(USERS.admin.email);
      log('## 1. Pilot scope');
      const p = await createPilot(direct.db, adminId, { investorId: await userId(A), instrumentId: BTC, exchangeAccountRef: 'MEXC UID …4821 (dry run)', ...LIMITS });
      log(`- Allowlist: investor ${A}, MEXC account "${p.exchangeAccountRef}", contract BTCUSDT (BTC_USDT). Adds: off. Automatic reversal: off.`);
      log(`- Operator-approved limits: max ${LIMITS.maxOrderContracts} contracts and ${LIMITS.maxOrderNotionalUsdt} USDT per order, max ${LIMITS.maxLeverage}x, max exposure ${LIMITS.maxExposureUsdt} USDT.`);
      await expect(approvePilot(direct.db, adminId, p.id)).rejects.toThrow(/checks recorded as passed/);
      await expect(activatePilot(direct.db, await userId(A))).rejects.toThrow(/not approved/);
      for (const c of Object.keys(PILOT_REQUIRED_CHECKS) as PilotCheckId[]) await recordPilotCheck(direct.db, adminId, p.id, c, { passed: true, evidence: 'DRY RUN — mock evidence only; must be redone on the real account' });
      await approvePilot(direct.db, adminId, p.id);
      await expect(activatePilot(direct.db, await userId(B))).rejects.toThrow(/No live pilot/);
      await activatePilot(direct.db, await userId(A));
      log('- Approval was refused until all six pre-pilot checks were recorded; activation was refused before approval and for investor B; investor A activated.');
      const tick = async () => recordMarketTick(direct.db, { instrumentId: BTC, asOf: clock.now, bid: '64999.5', ask: '65000.5', mark: '65000', last: '65000' });
      await tick();
      const { writeMarketFixture } = await import('@trendpilot/db');
      await writeMarketFixture(direct.db, { instrumentId: BTC, interval: '15', endBarOpen: new Date('2026-11-08T09:15:00Z'), count: 260, endClose: '65000', trend: 'UP', quoteAt: clock.now });
      mexc.faults.fillRatio = 0.6; // the first entry fills partially
    }
  });
});

afterAll(async () => {
  setTestClock(null);
  mkdirSync(path.join(ROOT, 'test-results'), { recursive: true });
  writeFileSync(path.join(ROOT, 'test-results', 'pilot-rehearsal.md'), out.join('\n') + '\n');
  await teardown();
});

describe('Step 12 dry run (mocked MEXC)', () => {
  it('entry: the opening request carries the stop; stop coverage equals the confirmed (partial) fill', async () => {
    log('', '## 2. Entry with the stop attached (partial fill)');
    const [open] = creates();
    expect(open).toMatchObject({ side: 1, type: 5, openType: 1, leverage: 5, lossTrend: 2, positionMode: 2, symbol: 'BTC_USDT' });
    expect(open!.stopLossPrice).toBeTruthy();
    log('Redacted opening request (dummy credentials; signature and key redacted):');
    code(redacted(open!));
    const p = (await openPos())!;
    const [i] = await intentsOf(A);
    const filled = D(i!.contracts).times('0.6').floor();
    expect(D(i!.contracts).lte(LIMITS.maxOrderContracts)).toBe(true);
    expect(D(p.contracts).eq(filled)).toBe(true);
    expect(D(p.stopContracts!).eq(filled)).toBe(true);
    expect(p.protectionStatus).toBe('PROTECTED');
    const stop = [...mexc.stops.values()].find((s) => s.state === 1)!;
    log(`- Requested ${D(i!.contracts).toFixed()} contracts; MEXC filled ${filled.toFixed()} (60 %). Stop at MEXC: ${stop.vol} contracts at ${stop.stopLossPrice} (lossTrend ${stop.lossTrend} = mark). Platform: ${D(p.contracts).toFixed()} contracts, stop covers ${D(p.stopContracts!).toFixed()} → PROTECTED.`);
    const [bi] = await intentsOf(B);
    expect(bi).toMatchObject({ state: 'REJECTED', stateReason: 'PILOT_INVESTOR_NOT_ALLOWLISTED' });
    expect(creates()).toHaveLength(1); // nothing was sent for B
    log(`- Investor B (same alert, not allowlisted): REJECTED PILOT_INVESTOR_NOT_ALLOWLISTED; no request sent.`);
  });

  it('take profit: a reduce-only market close that cannot flip; final position, fees and P&L reconcile', async () => {
    log('', '## 3. Take profit');
    const p = (await openPos())!;
    await priceAt(plus(clock.now, 30).toISOString(), D(p.takeProfitPrice!).plus(10).toFixed()); // reaching the target arms it
    await drain(clock.now, direct.db, hooks());
    expect(creates()[1]).toBeUndefined(); // nothing is sent on the first touch
    await priceAt(plus(clock.now, 30).toISOString(), D(p.takeProfitPrice!).minus(10).toFixed()); // the pullback through it closes
    await drain(clock.now, direct.db, hooks());
    const close = creates()[1]!;
    expect(close).toMatchObject({ side: 4, type: 5, reduceOnly: true, vol: D(p.contracts).toFixed() });
    log('Redacted close request:');
    code(redacted(close));
    const done = (await positionsOf(A))[0]!;
    expect(done).toMatchObject({ status: 'CLOSED', closeReason: 'TAKE_PROFIT' });
    expect(D(mexc.positions.get('BTC_USDT:1')!.holdVol).isZero()).toBe(true);
    expect(mexc.positions.get('BTC_USDT:2')).toBeUndefined();
    log(`- Closed by TAKE_PROFIT. MEXC: Long 0, no Short opened. Stop at MEXC: ${[...mexc.stops.values()].filter((s) => s.state === 1).length} active.`);
  });

  it('close on signal: CLOSE_LONG submits a reduce-only close for the held contracts', async () => {
    log('', '## 4. Close on signal');
    mexc.reset();
    await alert('BULLISH_FLIP', '2026-11-08T09:30:00Z');
    const p = (await openPos())!;
    expect(p.protectionStatus).toBe('PROTECTED');
    await alert('CLOSE_LONG', '2026-11-08T09:45:00Z');
    const close = creates()[1]!;
    expect(close).toMatchObject({ side: 4, reduceOnly: true, vol: D(p.contracts).toFixed() });
    expect((await positionsOf(A)).find((x) => x.id === p.id)).toMatchObject({ status: 'CLOSED', closeReason: 'SIGNAL_CLOSE' });
    expect(mexc.positions.get('BTC_USDT:2')).toBeUndefined();
    log(`- Entry ${D(p.contracts).toFixed()} contracts (full fill, stop covers ${D(p.stopContracts!).toFixed()}); CLOSE_LONG → side 4, reduceOnly, vol ${close.vol} → SIGNAL_CLOSE; no Short opened.`);
  });

  it('missing stop: emergency close runs, new entries halt, and stay halted until the operator resumes', async () => {
    log('', '## 5. Missing stop');
    mexc.reset();
    mexc.faults.attachStop = 'missing';
    await alert('BULLISH_FLIP', '2026-11-08T10:00:00Z');
    const p = (await positionsOf(A)).at(-1)!;
    expect(p).toMatchObject({ status: 'CLOSED', closeReason: 'PROTECTION_FAILURE' });
    expect(creates()[1]).toMatchObject({ side: 4, reduceOnly: true });
    expect(await pilot()).toMatchObject({ entriesHalted: true });
    expect((await pilot()).haltReason).toMatch(/^PROTECTION_FAILURE/);
    log(`- Fill without a confirmed stop → position UNPROTECTED → emergency reduce-only close filled (PROTECTION_FAILURE) → entries halted: "${(await pilot()).haltReason}".`);
    const sent = creates().length;
    await alert('BULLISH_FLIP', '2026-11-08T10:15:00Z');
    expect((await intentsOf(A)).filter((i) => i.kind === 'OPEN').at(-1)).toMatchObject({ state: 'REJECTED', stateReason: 'PILOT_ENTRIES_HALTED' });
    expect(creates()).toHaveLength(sent);
    log('- Next alert while halted: REJECTED PILOT_ENTRIES_HALTED; no request sent.');
    await resumePilotEntries(direct.db, adminId, (await pilot()).id, 'DRY RUN: account verified flat at MEXC; stop behaviour reviewed');
    log('- Operator resumed entries after confirming the account flat (resume is refused while an order is unresolved or a position is unprotected).');
  });

  it('timeout after submission: entries halt; the order is reconciled before any retry; closing stays available', async () => {
    log('', '## 6. Timeout after submission');
    mexc.reset();
    mexc.faults.timeoutAfterAccept = 1;
    mexc.faults.invisibleLookups = 2;
    await alert('BULLISH_FLIP', '2026-11-08T10:30:00Z');
    const i = (await intentsOf(A)).filter((x) => x.kind === 'OPEN').at(-1)!;
    expect(i.state).toBe('SUBMITTING');
    expect(await pilot()).toMatchObject({ entriesHalted: true });
    expect((await pilot()).haltReason).toMatch(/^UNCERTAIN_ORDER/);
    await expect(resumePilotEntries(direct.db, adminId, (await pilot()).id, 'try')).rejects.toThrow(/unresolved/);
    log(`- MEXC accepted the order but the response timed out and the order was not yet visible → intent SUBMITTING, entries halted ("${(await pilot()).haltReason}"); resume refused while unresolved.`);
    for (let k = 0; k < 6 && !(await openPos()); k++) await later(5);
    expect(creates().filter((b) => b.externalOid === i.clientOrderId)).toHaveLength(1);
    const p = (await openPos())!;
    expect(p.protectionStatus).toBe('PROTECTED');
    log(`- Reconciled by client order ID on a later attempt: FILLED ${D(p.contracts).toFixed()} contracts, stop verified. Orders sent with that client ID: 1 (no resend).`);
    await direct.db.transaction(async (tx) => requestExit(tx, { position: (await openPos())!, reason: 'MANUAL_CLOSE', now: clock.now }));
    await drain(clock.now, direct.db, hooks());
    expect((await positionsOf(A)).find((x) => x.id === p.id)).toMatchObject({ status: 'CLOSED', closeReason: 'MANUAL_CLOSE' });
    log('- With entries still halted, a manual close was accepted and filled (closing is never gated).');
    await resumePilotEntries(direct.db, adminId, (await pilot()).id, 'DRY RUN: uncertain order reconciled; account flat');
  });

  it('worker restart after the exchange filled: the new process reconciles; nothing is resent', async () => {
    log('', '## 7. Worker restart after a fill');
    mexc.reset();
    await priceAt('2026-11-08T11:00:03Z', '65000');
    expect(await deliver('BULLISH_FLIP', new Date('2026-11-08T10:45:00Z'))).toBe(202);
    const crash = { venue, afterSimulatorFill: () => Promise.reject(new Error('simulated crash after the exchange fill')) };
    await drain(clock.now, direct.db, crash);
    const i = (await intentsOf(A)).filter((x) => x.kind === 'OPEN').at(-1)!;
    expect(i.state).toBe('SUBMITTING');
    expect(await openPos()).toBeUndefined();
    venue = buildVenue(); // a new worker process with a fresh adapter instance
    for (let k = 0; k < 4 && !(await openPos()); k++) await later(5);
    expect(creates().filter((b) => b.externalOid === i.clientOrderId)).toHaveLength(1);
    expect((await openPos())!.protectionStatus).toBe('PROTECTED');
    log(`- The worker died after MEXC filled ${i.clientOrderId} and before the platform recorded it. Restart (adapter instance #${venueGen}) reconciled it by client order ID: one order at MEXC, position recorded once, stop verified.`);
    await alert('CLOSE_LONG', '2026-11-08T11:00:00Z');
    expect(await openPos()).toBeUndefined();
  });

  it('pilot limits refuse oversize, over-leveraged and add-on entries without contacting MEXC', async () => {
    log('', '## 8. Pilot limits');
    const p = await pilot();
    await direct.db.update(schema.livePilots).set({ maxOrderContracts: '5' }).where(eq(schema.livePilots.id, p.id));
    const before = mexc.creates().length;
    await alert('BULLISH_FLIP', '2026-11-08T11:15:00Z');
    expect((await intentsOf(A)).filter((x) => x.kind === 'OPEN').at(-1)).toMatchObject({ state: 'REJECTED', stateReason: 'PILOT_ORDER_SIZE' });
    await direct.db.update(schema.livePilots).set({ maxOrderContracts: LIMITS.maxOrderContracts, maxLeverage: 3 }).where(eq(schema.livePilots.id, p.id));
    await alert('BULLISH_FLIP', '2026-11-08T11:30:00Z');
    expect((await intentsOf(A)).filter((x) => x.kind === 'OPEN').at(-1)).toMatchObject({ state: 'REJECTED', stateReason: 'PILOT_LEVERAGE' });
    expect(mexc.creates().length).toBe(before);
    await direct.db.update(schema.livePilots).set({ maxLeverage: LIMITS.maxLeverage }).where(eq(schema.livePilots.id, p.id));
    log('- Max contracts lowered to 5 → REJECTED PILOT_ORDER_SIZE; max leverage lowered to 3x → REJECTED PILOT_LEVERAGE; no request sent. (Adds: see unit tests — an entry with an open position is refused PILOT_ADDS_DISABLED.)');
  });

  it('end of pilot: the account is flat at the exchange and every number reconciles with the exchange records', async () => {
    log('', '## 9. End state and reconciliation');
    await deactivatePilot(direct.db, await userId(A));
    expect((await pilot()).status).toBe('APPROVED');
    const allPos = await positionsOf(A);
    expect(allPos.every((p) => p.status === 'CLOSED')).toBe(true);
    expect([...mexc.positions.values()].every((p) => D(p.holdVol).isZero())).toBe(true);
    expect([...mexc.stops.values()].filter((s) => s.state === 1)).toHaveLength(0);
    // Fees and P&L against the simulated exchange's deal records (all orders of the run).
    const exchangeFees = [...mexc.deals.values()].flat().reduce((t, d) => t.plus(d.fee), D(0));
    const platformFees = allPos.reduce((t, p) => t.plus(p.feesUsdt), D(0));
    const exits = await direct.db.select().from(schema.positionExits).where(eq(schema.positionExits.ownerId, await userId(A)));
    // Realized P&L recomputed from the exchange's fill prices: (exit − entry) × contracts × multiplier.
    let exchangePnl = D(0);
    for (const x of exits) {
      const pos = allPos.find((p) => p.id === x.positionId)!;
      exchangePnl = exchangePnl.plus(D(x.price).minus(pos.avgEntryPrice).times(x.contracts).times('0.0001'));
    }
    const platformPnl = allPos.reduce((t, p) => t.plus(p.realizedPnlUsdt), D(0));
    const closeOrders = [...mexc.orders.values()].filter((o) => o.side === 4);
    const exitVolAtExchange = closeOrders.reduce((t, o) => t.plus(o.dealVol), D(0));
    const exitVolPlatform = exits.reduce((t, x) => t.plus(x.contracts), D(0));
    expect(platformFees.toDecimalPlaces(8).eq(exchangeFees.toDecimalPlaces(8))).toBe(true);
    expect(platformPnl.toDecimalPlaces(8).eq(exchangePnl.toDecimalPlaces(8))).toBe(true);
    expect(exitVolPlatform.eq(exitVolAtExchange)).toBe(true);
    expect(await reconciled()).toBe(true);
    log(`- Platform positions: ${allPos.length}, all CLOSED. MEXC (mock): every position 0, no active stop. Investor deactivated (pilot back to APPROVED).`);
    log(`- Fees: platform ${platformFees.toFixed()} USDT = exchange deal records ${exchangeFees.toFixed()} USDT.`);
    log(`- Closed volume: platform ${exitVolPlatform.toFixed()} = exchange close orders ${exitVolAtExchange.toFixed()} contracts. Realized P&L: platform ${platformPnl.toFixed()} = from exchange fill prices ${exchangePnl.toFixed()} USDT.`);
    log(`- Paper-ledger identity (wallet, margin, reserve vs ledger): ${(await reconciled()) ? 'holds' : 'BROKEN'}.`);
    const r = pilotReadiness(await pilot());
    log('', '## 10. Readiness after the dry run');
    log(`readyForFirstTrade: **${r.readyForFirstTrade}**, readyForExpansion: **${r.readyForExpansion}**`, '');
    log('| Stage | Item | State | Detail |', '| --- | --- | --- | --- |');
    for (const it of r.items) log(`| ${it.stage} | ${it.label} | ${it.state} | ${it.detail ?? ''} |`);
    expect(r.readyForFirstTrade).toBe(false);
    log('', '## Guard events', '');
    for (const e of events) log(`- ${e.kind}: ${e.reason}`);
    const audits = await direct.db.select({ action: schema.auditEvents.action }).from(schema.auditEvents).where(and(eq(schema.auditEvents.targetType, 'live_pilot')));
    log('', `Audit trail actions: ${[...new Set(audits.map((a) => a.action))].join(', ')}`);
    expect(audits.map((a) => a.action)).toEqual(expect.arrayContaining(['ADMIN_LIVE_PILOT_CREATE', 'ADMIN_LIVE_PILOT_CHECK', 'ADMIN_LIVE_PILOT_APPROVE', 'LIVE_PILOT_ACTIVATE', 'LIVE_PILOT_HALT', 'ADMIN_LIVE_PILOT_RESUME', 'LIVE_PILOT_DEACTIVATE']));
  });
});
